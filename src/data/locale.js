/**
 * Все строки интерфейса. Единственный источник правды для текстов —
 * в разметке и в JS не должно оставаться зашитых слов на русском.
 *
 * Ключи — вложенные, обращение через точку: t('nav.menu').
 * Названия и описания напитков живут отдельно, в data/menu.js.
 *
 * Дефис и тире внутри времени окружены word-joiner'ом \u2060: без него
 * строка рвётся по разделителю — «8:00-» уезжает на одну строку, аффикс
 * «ден» на следующую, а «08:00–» отрывается от «22:00». Word-joiner
 * запрещает перенос и глифа не требует: это невидимый управляющий символ,
 * его не рисует ни один шрифт. Неразрывный дефис U+2011 сюда не годится —
 * в Inter его нет, он молча ушёл бы в фолбэк.
 *
 * Записываем строго escape'ом (\u2060), а не самим символом: невидимый знак
 * в тексте не видно в редакторе и не видно в diff'е, поэтому первая же правка
 * словаря его потеряет — и никто не заметит, пока строка снова не сломается.
 */

